function makeQuestion(
  lessonId: string,
  mode: "assessment" | "remedial",
  index: number,
  draft: QuestionDraft,
): VerbalQuestion {
  const [prompt, options, correctOptionIndex, explanation, passageLabel, passageText] = draft;
  return {
    id: `${lessonId}-${mode === "assessment" ? "a" : "r"}${index + 1}`,
    skillCode: lessonId,
    prompt,
    options,
    correctOptionIndex,
    explanation,
    optionFeedback: options.map((_, optionIndex) =>
      optionIndex === correctOptionIndex
        ? null
        : `هذا الخيار لا يوافق القرينة المطلوبة. ${explanation}`,
    ),
    ...(passageLabel && passageText ? { passageLabel, passageText } : {}),
  };
}

function buildLesson(topic: Topic, topicIndex: number, chapterIndex: number): VerbalLesson {
  const draft = lessonDrafts[topic.id];
  if (!draft) throw new Error(`Missing reviewed verbal lesson draft: ${topic.id}`);
  const bank = banks[chapterIndex];
  const firstSupplementalIndex = chapterIndex === 4 ? 2 : 1;
  const start = (topicIndex - firstSupplementalIndex) % 8;
  const assessmentQuestions = Array.from({ length: 4 }, (_, index) =>
    makeQuestion(topic.id, "assessment", index, bank.assessment[(start + index) % bank.assessment.length]),
  );
  const remedialQuestions = Array.from({ length: 4 }, (_, index) =>
    makeQuestion(topic.id, "remedial", index, bank.remedial[(start + index) % bank.remedial.length]),
  );

  return {
    id: topic.id,
    title: topic.title,
    summary: draft.summary,
    estimatedMinutes: chapterIndex === 4 ? 12 : 10,
    sources: [],
    sections: [
      {
        id: `${topic.id}-concept`,
        kind: "concept",
        title: "الفكرة الأساسية",
        paragraphs: [
          draft.summary,
          "حلل المطلوب قبل النظر إلى الخيارات، واستند إلى قرينة واضحة من الجملة أو النص بدل التخمين أو المعرفة الخارجية.",
        ],
        workedExample: { question: draft.example, steps: draft.steps, answer: draft.answer },
      },
      {
        id: `${topic.id}-method`,
        kind: "rule",
        title: "خطوات الحل",
        paragraphs: [
          draft.rule,
          "بعد الاختيار، أعد قراءة العبارة كاملة وتأكد أن الإجابة تفسر الدليل ولا تضيف تعميمًا أو افتراضًا.",
        ],
      },
      {
        id: `${topic.id}-warning`,
        kind: "warning",
        title: "انتبه إلى المشتت",
        paragraphs: [
          "قد يبدو أحد الخيارات مرتبطًا بالموضوع لكنه لا يجيب عن المطلوب تحديدًا. قارن العلاقة أو الدلالة كاملة، لا كلمة منفردة.",
        ],
      },
    ],
    assessmentQuestions,
    remedialQuestions,
  };
}

export function createSupplementalVerbalLessons(topics: Topic[], publishedIds: Set<string>) {
  return topics.flatMap((topic, index) => {
    if (publishedIds.has(topic.id)) return [];
    const chapterIndex = Math.floor(index / 10);
    const topicIndex = index % 10;
    return [buildLesson(topic, topicIndex, chapterIndex)];
  });
}
